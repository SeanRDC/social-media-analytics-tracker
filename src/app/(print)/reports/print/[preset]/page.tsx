import type { Metadata } from "next";
import { notFound } from "next/navigation";
import { Suspense } from "react";
import { PrintButton } from "@/components/reports/PrintButton";
import s from "@/components/reports/Print.module.css";
import { APP_NAME } from "@/lib/brand";
import { getReportData } from "@/lib/data/api";
import { formatNumber } from "@/lib/format";
import { buildReport, isPreset, PRESETS, type Cell } from "@/lib/reports/build";

export async function generateMetadata({ params }: PageProps<"/reports/print/[preset]">): Promise<Metadata> {
  const { preset } = await params;
  return { title: PRESETS.find((p) => p.id === preset)?.title ?? "Report", robots: { index: false } };
}

/** A print-ready report: the browser's print dialog saves it as a PDF. */
export default function PrintPage({ params }: PageProps<"/reports/print/[preset]">) {
  return (
    <Suspense fallback={<p className={s.loading}>Preparing your report…</p>}>
      <Report params={params} />
    </Suspense>
  );
}

const cell = (c: Cell) => (typeof c === "number" ? formatNumber(c) : c);

async function Report({ params }: Pick<PageProps<"/reports/print/[preset]">, "params">) {
  const { preset } = await params;
  if (!isPreset(preset)) notFound();
  const data = await getReportData();
  const r = buildReport(preset, data);
  return (
    <main className={s.page}>
      <div className={s.toolbar}>
        <a href="/reports" className={s.back}>
          Back to reports
        </a>
        <PrintButton />
      </div>
      <header className={s.head}>
        <span className={s.brand}>{APP_NAME}</span>
        <h1>{r.title}</h1>
        <p className={s.period}>{r.period}</p>
        {r.note && <p className={s.note}>{r.note}</p>}
      </header>
      {r.sections.map((sec) => (
        <section key={sec.heading} className={s.section}>
          <h2>{sec.heading}</h2>
          {sec.rows.length ? (
            <table>
              <thead>
                <tr>
                  {sec.columns.map((c) => (
                    <th key={c} scope="col">
                      {c}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {sec.rows.map((row, i) => (
                  <tr key={i}>
                    {row.map((c, j) => (
                      <td key={j} className={typeof c === "number" ? s.num : undefined}>
                        {sec.columns[j] === "Link" && c ? (
                          <a href={String(c)}>Open</a>
                        ) : (
                          cell(c)
                        )}
                      </td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          ) : (
            <p className={s.empty}>Nothing in this period yet.</p>
          )}
        </section>
      ))}
      <footer className={s.foot}>
        Generated by {APP_NAME} · numbers as of {data.asOf}
      </footer>
    </main>
  );
}
